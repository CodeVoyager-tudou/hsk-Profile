# 平分时优先顺序：非 disease 优先，避免"泛泛问题"全部落回 disease
_PRIORITY = ["order", "mall", "medication", "lab", "lifestyle", "risk", "disease"]

# 高辨识度关键词：命中一个就足以判定意图，计 2 分（普通词计 1 分）。
#
# 为什么需要它：LLM 路由成功时的并集补充阈值是 min_score=2（见 RouterAgent.route），
# 于是"只有一个数据意图词"的问句会被漏掉 —— 实测「阿司匹林肠溶片多少钱？」里
# mall 只命中「多少钱」1 分，LLM 又只选了 medication，结果商城专家没被叫上，
# 回答里就没有价格（而「…多少钱？用积分要多少积分？」因为凑满 2 分反而正常）。
# 这类词本身没有歧义（问价格/订单不会是在问医学知识），所以给它们双倍权重。
STRONG_KEYWORDS = {
    # 问价/资产：命中即应查商品表或账户，不该由模型凭常识回答
    "mall": {"多少钱", "价格", "售价", "卖多少", "怎么卖", "多少积分", "积分兑换",
             "优惠券", "余额", "原价"},
    # 订单事务与消费汇总：命中即应查订单表（"订单"/"花了多少"这类说法不会出现在医学知识问句里）
    "order": {"订单", "订单号", "退款", "待支付", "待付款", "已支付", "已付款", "已取消",
              "物流", "快递",
              # 汇总意图（"我最近30天花了多少钱"）：与 OrderAgent 的汇总正则同源。
              # 只放无歧义的：总共/一共/统计 这类词在用药问句里也会出现（"一天一共吃几次"），
              # 留在弱词表里计 1 分即可，给 2 分会把订单专家误叫进来。
              "花了", "消费", "花费", "合计", "多少笔", "几笔", "多少单"},
}


def _score(agent: str, query: str) -> int:
    """单个专家的关键词得分：高辨识度词计 2 分，其余计 1 分"""
    strong = STRONG_KEYWORDS.get(agent, ())
    return sum(2 if kw in strong else 1 for kw in AGENT_KEYWORDS[agent] if kw in query)


def keyword_route(query: str) -> Tuple[Optional[str], int]:
    """对问题做关键词打分，返回 (命中专家, 得分)。

    得分 >= 1 视为有命中；得分高表示意图越明确。
    返回 (None, 0) 表示未命中任何专家（交由 LLM 处理或走 disease 兜底）。
    """
    q = (query or "").lower()
    best_agent, best_score = None, 0
    for agent in _PRIORITY:
        score = _score(agent, q)
        # 严格大于才替换：_PRIORITY 顺序在前者平分时优先
        if score > best_score:
            best_agent, best_score = agent, score
    return best_agent, best_score


def keyword_routes(query: str, min_score: int = 1) -> list:
    """返回所有得分 >= min_score 的专家列表（按优先级排序），供并集补充/兜底使用。

    min_score=2 表示仅高置信命中（用于 LLM 成功时并回，避免低置信误加入）；
    min_score=1 表示任一命中（用于 LLM 失败时兜底）。
    """
    q = (query or "").lower()
    result = []
    for agent in _PRIORITY:
        if _score(agent, q) >= min_score:
            result.append(agent)
    return result
